// Builds the Supabase setup script (see scripts/supabase-sql.ts). Migrations are recorded in
// drizzle.__drizzle_migrations with the same hash and timestamp drizzle's migrator writes, so
// `pnpm db:migrate` and this script agree on what has run.
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { BOOKS, MARKETS, teams } from '@hiddengems/core';
import { migrationsFolder } from './client';

export const APP_ROLE = 'hiddengems_app';
/** Previews read production through this login: select only, read-only transactions. Its password is the owner's. */
export const PREVIEW_ROLE = 'hiddengems_preview';

const lit = (v: string) => `'${v.replace(/'/g, "''")}'`;

export function migrationStatements(folder = migrationsFolder()): { tag: string; when: number; hash: string; statements: string[] }[] {
  const journal = JSON.parse(readFileSync(join(folder, 'meta/_journal.json'), 'utf8')) as { entries: { tag: string; when: number }[] };
  return journal.entries.map((e) => {
    const sql = readFileSync(join(folder, `${e.tag}.sql`), 'utf8');
    return {
      tag: e.tag, when: e.when, hash: createHash('sha256').update(sql).digest('hex'),
      statements: sql.split('--> statement-breakpoint').map((s) => s.trim()).filter(Boolean),
    };
  });
}

/** The migrations and reference data, plain Postgres (also run against PGlite in tests). */
export function migrationSql(folder?: string): string {
  const out = [
    'CREATE SCHEMA IF NOT EXISTS "drizzle";',
    'CREATE TABLE IF NOT EXISTS "drizzle"."__drizzle_migrations" (id SERIAL PRIMARY KEY, hash text NOT NULL, created_at bigint);',
  ];
  migrationStatements(folder).forEach((m, i) => {
    const body = m.statements.map((s, j) => `    EXECUTE $hg_${i}_${j}$${s}$hg_${i}_${j}$;`).join('\n');
    out.push(`-- ${m.tag}
DO $hg_m${i}$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM "drizzle"."__drizzle_migrations" WHERE created_at = ${m.when}) THEN
${body}
    INSERT INTO "drizzle"."__drizzle_migrations" (hash, created_at) VALUES (${lit(m.hash)}, ${m.when});
  END IF;
END $hg_m${i}$;`);
  });
  out.push('-- Reference data');
  out.push(`INSERT INTO teams (id, abbr, city, name, conference, division) VALUES\n${teams.map((t) => `  (${[t.id, t.abbr, t.city, t.name, t.conference, t.division].map(lit).join(', ')})`).join(',\n')}\nON CONFLICT (id) DO UPDATE SET abbr = excluded.abbr, city = excluded.city, name = excluded.name, conference = excluded.conference, division = excluded.division;`);
  out.push(`INSERT INTO books (id, name) VALUES ${BOOKS.map((b) => `(${lit(b.id)}, ${lit(b.name)})`).join(', ')} ON CONFLICT (id) DO UPDATE SET name = excluded.name;`);
  out.push(`INSERT INTO markets (id, label) VALUES ${MARKETS.map((m) => `(${lit(m.id)}, ${lit(m.label)})`).join(', ')} ON CONFLICT (id) DO UPDATE SET label = excluded.label;`);
  return out.join('\n\n');
}

export function buildSupabaseSql({ appPassword, folder }: { appPassword?: string; folder?: string } = {}): string {
  if (appPassword !== undefined && !/^[A-Za-z0-9]{24,}$/.test(appPassword)) {
    throw new Error('Use a password of at least 24 letters and digits, so it needs no escaping in a connection string');
  }
  const role = appPassword === undefined ? '' : `
-- The app's own login: rows only. It cannot create, alter, drop or truncate anything.
DO $hg_role$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = ${lit(APP_ROLE)}) THEN
    CREATE ROLE ${APP_ROLE} LOGIN PASSWORD ${lit(appPassword)};
  ELSE
    ALTER ROLE ${APP_ROLE} LOGIN PASSWORD ${lit(appPassword)};
  END IF;
END $hg_role$;`;
  const grants = `
-- Grants for the app login (skipped until it exists).
DO $hg_grants$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = ${lit(APP_ROLE)}) THEN
    GRANT USAGE ON SCHEMA public TO ${APP_ROLE};
    GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO ${APP_ROLE};
    GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO ${APP_ROLE};
    ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${APP_ROLE};
    ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO ${APP_ROLE};
  END IF;
END $hg_grants$;

-- The preview login: reads every app table, changes nothing. Created without a login; the owner sets its
-- password in the Supabase SQL editor (docs/architecture.md, "Previews") and puts it in Vercel's Preview DATABASE_URL.
DO $hg_preview$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = ${lit(PREVIEW_ROLE)}) THEN
    CREATE ROLE ${PREVIEW_ROLE} NOLOGIN;
  END IF;
  ALTER ROLE ${PREVIEW_ROLE} SET default_transaction_read_only = on;
  GRANT USAGE ON SCHEMA public TO ${PREVIEW_ROLE};
  GRANT SELECT ON ALL TABLES IN SCHEMA public TO ${PREVIEW_ROLE};
  ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO ${PREVIEW_ROLE};
END $hg_preview$;`;
  return `-- Hidden Gems database setup for Supabase, generated by \`pnpm db:supabase-sql\`.
-- Paste into Supabase, SQL Editor, New query, and press Run. Safe to run again.
BEGIN;

${migrationSql(folder)}

-- Close Supabase's automatic public API on the app's tables. The app connects to Postgres directly.
DO $hg_api$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated;
    REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
    REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM anon, authenticated;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON TABLES FROM anon, authenticated;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON SEQUENCES FROM anon, authenticated;
    ALTER DEFAULT PRIVILEGES IN SCHEMA public REVOKE ALL ON FUNCTIONS FROM anon, authenticated;
  END IF;
END $hg_api$;
${role}
${grants}

COMMIT;
`;
}
